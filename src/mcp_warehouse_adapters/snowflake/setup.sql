-- One-time Snowflake setup for cpg-analytics-mcp (trial / personal account only, synthetic data only).
-- Run with `uv run mwa-snowflake-setup`: it fills <PUBLIC_KEY> in memory from SNOWFLAKE_PUBLIC_KEY_PATH
-- and runs this file as ACCOUNTADMIN. Never paste a real key into this file; a test enforces that.
-- Re-runnable: every statement is IF NOT EXISTS or idempotent.

USE ROLE ACCOUNTADMIN;

-- Compute: smallest warehouse, suspends after 60s idle.
CREATE WAREHOUSE IF NOT EXISTS CPG_WH
  WAREHOUSE_SIZE = XSMALL AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE;

-- Cost governance: cap credits so the trial cannot run away.
CREATE RESOURCE MONITOR IF NOT EXISTS CPG_MONITOR WITH
  CREDIT_QUOTA = 10 FREQUENCY = MONTHLY START_TIMESTAMP = IMMEDIATELY
  TRIGGERS ON 80 PERCENT DO NOTIFY
           ON 100 PERCENT DO SUSPEND;
ALTER WAREHOUSE CPG_WH SET RESOURCE_MONITOR = CPG_MONITOR;

-- Storage.
CREATE DATABASE IF NOT EXISTS CPG_MCP;
CREATE SCHEMA IF NOT EXISTS CPG_MCP.MAIN;

-- Roles: one loader that owns objects, one read-only role per server role in roles.yaml.
CREATE ROLE IF NOT EXISTS CPG_LOADER;
CREATE ROLE IF NOT EXISTS CPG_ANALYST;
CREATE ROLE IF NOT EXISTS CPG_SALES;
CREATE ROLE IF NOT EXISTS CPG_FINANCE;
GRANT ROLE CPG_LOADER TO ROLE SYSADMIN;
GRANT ROLE CPG_ANALYST TO ROLE SYSADMIN;
GRANT ROLE CPG_SALES TO ROLE SYSADMIN;
GRANT ROLE CPG_FINANCE TO ROLE SYSADMIN;

GRANT USAGE ON WAREHOUSE CPG_WH TO ROLE CPG_LOADER;
GRANT USAGE ON WAREHOUSE CPG_WH TO ROLE CPG_ANALYST;
GRANT USAGE ON WAREHOUSE CPG_WH TO ROLE CPG_SALES;
GRANT USAGE ON WAREHOUSE CPG_WH TO ROLE CPG_FINANCE;
GRANT USAGE ON DATABASE CPG_MCP TO ROLE CPG_LOADER;
GRANT USAGE ON DATABASE CPG_MCP TO ROLE CPG_ANALYST;
GRANT USAGE ON DATABASE CPG_MCP TO ROLE CPG_SALES;
GRANT USAGE ON DATABASE CPG_MCP TO ROLE CPG_FINANCE;
GRANT USAGE ON SCHEMA CPG_MCP.MAIN TO ROLE CPG_LOADER;
GRANT USAGE ON SCHEMA CPG_MCP.MAIN TO ROLE CPG_ANALYST;
GRANT USAGE ON SCHEMA CPG_MCP.MAIN TO ROLE CPG_SALES;
GRANT USAGE ON SCHEMA CPG_MCP.MAIN TO ROLE CPG_FINANCE;

-- Only the loader can create objects. SELECT grants and masking policies are applied by the loader
-- from roles.yaml (see src/mcp_warehouse_adapters/snowflake/governance.py).
-- Data is bulk-loaded through each table's own stage (@%table), so no CREATE STAGE privilege is needed.
GRANT CREATE TABLE, CREATE VIEW, CREATE MASKING POLICY
  ON SCHEMA CPG_MCP.MAIN TO ROLE CPG_LOADER;

-- Service user: key-pair only (TYPE = SERVICE cannot log in with a password).
CREATE USER IF NOT EXISTS CPG_MCP_SVC
  TYPE = SERVICE
  RSA_PUBLIC_KEY = '<PUBLIC_KEY>'
  DEFAULT_ROLE = CPG_ANALYST
  DEFAULT_WAREHOUSE = CPG_WH
  DEFAULT_NAMESPACE = CPG_MCP.MAIN
  DEFAULT_SECONDARY_ROLES = ();  -- only the primary role counts (the adapter also enforces this)
ALTER USER CPG_MCP_SVC SET DEFAULT_SECONDARY_ROLES = ();
GRANT ROLE CPG_LOADER TO USER CPG_MCP_SVC;
GRANT ROLE CPG_ANALYST TO USER CPG_MCP_SVC;
GRANT ROLE CPG_SALES TO USER CPG_MCP_SVC;
GRANT ROLE CPG_FINANCE TO USER CPG_MCP_SVC;
